func digest(data []byte) string { sum := sha256.Sum256(data); return hex.EncodeToString(sum[:]) }
func profileProofBinding(l *profile.Link) string {
	if l == nil {
		return ""
	}
	copy := *l
	copy.Remark, copy.Group, copy.SourceID = "", "", ""
	copy.HTTPSCapable, copy.ListenPort = 0, 0
	copy.ChainProxy = ""
	data, _ := json.Marshal(copy)
	return digest(data)
}
func bindSessionProof(p *PathProof, session *bench.Session, link *profile.Link) error {
	// Certify the actual file used by the owned engine, not separately generated bytes.
	data, err := os.ReadFile(session.ConfigFile)
	if err != nil || digest(data) != digest(session.Config) || !session.EngineOwned {
		return errors.New("cannot bind proof to the engine-owned configuration")
	}
	p.ProofVersion = "P5"
	p.ConfigSHA256 = digest(data)
	p.ProfileSHA256 = profileProofBinding(link)
	p.EngineOwned = true
	return nil
}

// VerifiedTestResult is the single fail-closed predicate shared by backend/TUI.
// Old status=ok rows, TCP-only results and stale proofs are never certified.
func VerifiedTestResult(r TestResult) bool {
	p := r.Path
	if r.Status != TestStatusOK || r.Category != CategoryVerified || r.Stale || r.Superseded || resultStale(r.TestedAt) || p == nil {
		return false
	}
	if p.ProofVersion != "P5" || p.Kind != "isolated" || p.Level != "L1+L2" || p.ConfigAudit != "pass" || !p.IsolationVerified || !p.EngineOwned || !p.TunneledHTTPS || len(p.ConfigSHA256) != 64 || len(p.ProfileSHA256) != 64 {
		return false
	}
	if net.ParseIP(p.UplinkIP) == nil || net.ParseIP(p.ExitBefore) == nil || p.ExitBefore != p.ExitAfter || p.ExitBefore == p.UplinkIP || (p.ServingExitIP != "" && p.ExitBefore == p.ServingExitIP) {
		return false
	}
	if len(p.Echoes) < 2 || p.Echoes[0].Service == "" || p.Echoes[0].Service == p.Echoes[1].Service {
		return false
	}
	for _, echo := range p.Echoes {
		if echo.IP != p.ExitBefore {
			return false
		}
	}
	if r.Kind == TestKindSpeed {
		return r.MBps > 0 && r.Bytes > 0 && r.Seconds > 0
	}
	return r.P50MS > 0 || r.LatencyMS > 0
}

func attemptCategory(err error) string {
	var attempt *bench.AttemptError
	if errors.As(err, &attempt) {
		return attempt.Category
	}
	var parse *profile.ParseError
	if errors.As(err, &parse) {
		return parse.Category
	}
	var cert *tls.CertificateVerificationError
	var unknown x509.UnknownAuthorityError
	var invalid x509.CertificateInvalidError
	var hostname x509.HostnameError
	if errors.As(err, &cert) || errors.As(err, &unknown) || errors.As(err, &invalid) || errors.As(err, &hostname) {
		return CategoryHandshake
	}
	var op *net.OpError
	if errors.As(err, &op) || errors.Is(err, context.DeadlineExceeded) {
		return CategoryUnreachable
	}
	return CategoryInfrastructure
}
func failAttempt(res *TestResult, err error, parent context.Context) {
	if errors.Is(parent.Err(), context.Canceled) || errors.Is(err, context.Canceled) {
		res.Status, res.Detail = TestStatusCancelled, "test cancelled by user"
		return
	}
	res.Status = TestStatusFailed
	res.Category = attemptCategory(err)
	// Engine and network errors can quote secret-bearing config contents. Keep
	// the category, never the untrusted message, in persisted diagnostics.
	res.Detail = "test attempt failed: " + res.Category
	if errors.Is(err, context.DeadlineExceeded) {
		res.Detail = "test attempt timed out"
	}
}
func finishAttempt(res *TestResult, parent context.Context) {
	if parent.Err() == context.Canceled {
		res.Status, res.Detail = TestStatusCancelled, "test cancelled by user"
		zeroMeasurement(res)
	}
	if res.Status == "" {
		res.Status, res.Category, res.Detail = TestStatusFailed, CategoryUnreachable, "test attempt timed out or did not complete"
	}
	if res.Category == "" {
		switch res.Status {
		case TestStatusOK:
			res.Category = CategoryVerified
		case TestStatusInconclusive:
			res.Category = CategoryExitUnverified
		case TestStatusUnavailable:
			res.Category = CategoryUnsupported
		case TestStatusFailed:
			res.Category = CategoryUnreachable
		}
	}
	if res.Status == TestStatusOK && !VerifiedTestResult(*res) {
		res.Status, res.Category, res.Reason = TestStatusInconclusive, CategoryExitUnverified, ReasonExitUnknown
		res.Detail = "HTTPS answered, but the isolated engine-owned path and independent exit identity are not fully verified"
		zeroMeasurement(res)
	}
}

// InvalidateSupersededResults retains honest history but prevents an older
// success (including a speed proof) surviving a later failed/inconclusive try.
func InvalidateSupersededResults(results []TestResult) {
	latestFailure := map[string]TestResult{}
	for _, r := range results {
		if r.Status == TestStatusOK || r.Status == TestStatusSkipped {
			continue
		}
		if cur, ok := latestFailure[r.ConnectionID]; !ok || TestResultAtLeastAsNew(r, cur) {
			latestFailure[r.ConnectionID] = r
		}
	}
	for i := range results {
		last, ok := latestFailure[results[i].ConnectionID]
		if ok && TestResultAtLeastAsNew(last, results[i]) && results[i].Status == TestStatusOK {
			results[i].Superseded = true
		}
	}
}

func TestResultAtLeastAsNew(a, b TestResult) bool {
	at, ae := time.Parse(time.RFC3339Nano, a.TestedAt)
	bt, be := time.Parse(time.RFC3339Nano, b.TestedAt)
	if ae != nil {
		return be != nil
	}
	if be != nil {
		return true
	}
	return !at.Before(bt)
}

func proofTimestamp() string { return time.Now().UTC().Format(time.RFC3339Nano) }
